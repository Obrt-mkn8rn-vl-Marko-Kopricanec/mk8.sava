    private static readonly int[][] WeightLevels = [PrimaryWeights, SecondaryWeights, SymbolWeights];

    private AzureCanonicalHeaderNameComparer()
    {
    }

    public int Compare(string? x, string? y)
    {
        if (ReferenceEquals(x, y))
            return 0;
        if (x is null)
            return -1;
        if (y is null)
            return 1;

        for (var level = 0; level < WeightLevels.Length; level++)
        {
            var leftIndex = 0;
            var rightIndex = 0;
            while (true)
            {
                if (level == WeightLevels.Length - 1 && leftIndex != rightIndex)
                    return rightIndex - leftIndex;

                var leftWeight = GetWeight(WeightLevels[level], x, leftIndex);
                var rightWeight = GetWeight(WeightLevels[level], y, rightIndex);
                if (leftWeight == 1 && rightWeight == 1)
                    break;
                if (leftWeight == rightWeight)
                {
                    leftIndex++;
                    rightIndex++;
                }
                else if (leftWeight == 0)
                {
                    leftIndex++;
                }
                else if (rightWeight == 0)
                {
                    rightIndex++;
                }
                else
                {
                    return leftWeight - rightWeight;
                }
            }
        }

        return 0;
    }

    private static int GetWeight(int[] level, string value, int index) =>
        index >= value.Length ? 1 : level[value[index]];
